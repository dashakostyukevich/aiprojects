COLS = 4
ROWS = 9
TOTAL = COLS * ROWS          # 36


def board_cells():
    """Змейка: 1..36 по 4 колонкам и 9 строкам."""
    cells = []
    for i in range(TOTAL):
        row, pos = divmod(i, COLS)
        col = pos if row % 2 == 0 else COLS - 1 - pos
        cells.append((i + 1, row, col))
    return cells


ARROWS = {(-1, 0): "←", (1, 0): "→", (0, 1): "↓", (0, -1): "↑"}


def arrow_for(n):
    """Стрелка к следующей клетке (по змейке)."""
    if n >= TOTAL:
        return "◼"
    r1, p1 = divmod(n - 1, COLS)
    c1 = p1 if r1 % 2 == 0 else COLS - 1 - p1
    r2, p2 = divmod(n, COLS)
    c2 = p2 if r2 % 2 == 0 else COLS - 1 - p2
    return ARROWS.get((c2 - c1, r2 - r1), "→")


def cell_kind(n):
    if n == 1:
        return ("start", None, None)
    if n == TOTAL:
        return ("finish", None, None)
    if n >= 32:
        idx = n - 32
        if idx < len(SPECIALS):
            return ("spec", None, SPECIALS[idx])
        return ("spec", None, SPECIALS[-1])
    return ("sec", SECTORS[list(SECTORS)[(n - 2) // 6]], None)


