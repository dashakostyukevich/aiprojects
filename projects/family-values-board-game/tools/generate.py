def build_pdf(html_path=OUT_HTML, pdf_path=OUT_PDF):
    if not os.path.exists(CHROME):
        print("Chrome не найден, PDF не собран:", CHROME)
        return False
    os.makedirs(DIST_DIR, exist_ok=True)
    cmd = [
        CHROME,
        "--headless=new",
        "--disable-gpu",
        "--no-pdf-header-footer",
        "--print-to-pdf=" + pdf_path,
        "file://" + html_path,
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
    if not os.path.exists(pdf_path):
        print("PDF не создан. stdout:", res.stdout, "stderr:", res.stderr)
        return False
    print("PDF готов:", pdf_path)
    return True


def main():
    os.makedirs(PRINT_DIR, exist_ok=True)
    os.makedirs(DIST_DIR, exist_ok=True)
    html_text = build_html()
    with open(OUT_HTML, "w", encoding="utf-8") as f:
        f.write(html_text)
    print("HTML готов:", OUT_HTML, "(%d КБ)" % (len(html_text.encode("utf-8")) // 1024))
    if "--no-pdf" not in sys.argv:
        build_pdf()


